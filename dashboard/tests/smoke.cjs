const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const folder=path.resolve(__dirname,'..');
const snap=fs.readFileSync(path.join(folder,'data/snapshot.js'),'utf8');
const context={window:{}};vm.runInNewContext(snap,context);
const d=context.window.PHOTONIQ_SNAPSHOT;
assert.equal(d.run_metadata.valid_joined_films,517);
assert.equal(d.run_metadata.n_wavelengths,351);
assert.equal(d.run_metadata.distinct_fabrication_dates,20);
assert.equal(d.verification.verified,true);
assert.equal(d.cross_validation_summary.length,14);
const map=new Map(d.cross_validation_summary.map(x=>[x.model,x]));
assert(Math.abs(map.get('CNN - 64 wavelengths').MAE_nm-69.27685663632776)<1e-8);
assert(Math.abs(map.get('CNN - 351 wavelengths').MAE_nm-78.02820666433072)<1e-8);
assert(Math.abs(map.get('Ridge - 351 wavelengths').MAE_nm-106.70807246490419)<1e-8);
assert(d.per_fold_metrics.length===70);
for(const group of new Set(d.per_fold_metrics.map(x=>x.fold)))assert.equal(d.per_fold_metrics.filter(x=>x.fold===group).length,14);
assert.equal(d.error_diagnostics.filter(x=>x.dimension==='fabrication_date').length,20);
assert.equal(d.error_diagnostics.filter(x=>x.dimension==='thickness_bin').reduce((s,x)=>s+x.n_films,0),517);
assert.equal(d.run_metadata.source_sha256.length,64);
assert(fs.readFileSync(path.join(folder,'index.html'),'utf8').includes('data/snapshot.js'));
console.log('PhotonIQ dashboard: all 13 scientific snapshot and structure checks passed.');
